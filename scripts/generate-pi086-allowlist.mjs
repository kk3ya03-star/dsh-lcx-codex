import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'

const snapshotPath = new URL('../data/pi086-responses-models.json', import.meta.url)
const outputPath = new URL('../src/pi086-responses-allowlist.ts', import.meta.url)
const snapshot = JSON.parse(readFileSync(snapshotPath, 'utf8'))
const providers = [
  'cloudflare-ai-gateway', 'github-copilot', 'openai',
  'opencode', 'opencode-go', 'xai',
]
assert.deepEqual(Object.keys(snapshot), providers)
for (const ids of Object.values(snapshot)) {
  assert.ok(Array.isArray(ids))
  assert.ok(ids.every(id => typeof id === 'string' && id.length > 0))
  assert.deepEqual(ids, [...new Set(ids)].sort())
}

const output = [
  '// Generated by scripts/generate-pi086-allowlist.mjs from the Pi 0.86.0',
  '// openai-responses catalog snapshot in data/pi086-responses-models.json.',
  '// Source: Issue #90 Step 0(c) probe/dump.mjs, runtime/pi-catalog/catalog-v0.86.0.json.',
  '// Keep provider and model paired: an id on another provider has separate authority.',
  `const responsesModels = ${JSON.stringify(snapshot, null, 2)} as const;`,
  '',
  'export function wasPi086ResponsesModel(provider: string, model: string): boolean {',
  '  const ids: readonly string[] | undefined = (responsesModels as Record<string, readonly string[]>)[provider];',
  '  return ids?.includes(model) ?? false;',
  '}',
  '',
].join('\n')

if (process.argv.includes('--check'))
  assert.equal(readFileSync(outputPath, 'utf8'), output, 'Pi 0.86.0 allowlist drifted from its pinned snapshot')
else writeFileSync(outputPath, output)
